-- enrollments.tenant_id is NOT NULL and used for tenant isolation but had no FK constraint.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'fk_enrollments_tenant'
  ) THEN
    ALTER TABLE enrollments ADD CONSTRAINT fk_enrollments_tenant FOREIGN KEY (tenant_id) REFERENCES tenants(id);
  END IF;
END $$;
